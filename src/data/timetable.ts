export type Schedule = 'weekday' | 'saturday' | 'holiday';

export type Route = {
  id: '01' | '02';
  label: string;
  sub: string;
  platform: string;
  direction: string;
  duration: number;
  times: Record<Schedule, number[]>;
};

function t(h: number, m: number): number {
  return h * 60 + m;
}

export function getSchedule(date?: Date): Schedule {
  const day = (date ?? new Date()).getDay();
  if (day === 0) return 'holiday';  // 日曜は休日ダイヤ
  if (day === 6) return 'saturday';
  return 'weekday';
}

